#!/usr/bin/env bash
#
# Builds the Wharf mobile SSH engine (sshengine/) into native binding artifacts
# with gomobile bind:
#   iOS     -> sshengine/dist/WharfSshEngine.xcframework  (device + simulator)
#   Android -> sshengine/dist/sshengine.aar               (needs an NDK)
#
# Usage:
#   ./scripts/build-ssh-engine.sh              # both targets (as available)
#   ./scripts/build-ssh-engine.sh --android    # aar only
#   ./scripts/build-ssh-engine.sh --ios        # xcframework only
#
# Target selection matters: gomobile output is NOT reproducible — rebuilding a
# target rewrites its bytes even with no source change. The iOS xcframework is
# committed, so an unwanted iOS rebuild shows up as ~35 MB of phantom diff. Build
# only what you actually need. The Android aar is git-ignored and regenerated by
# the wharf-ssh Gradle module on demand (modules/wharf-ssh/android/build.gradle).
set -euo pipefail

# Pinned so every machine and every EAS build produces the engine with the same
# gomobile. Floating @latest silently gives different builders different binding
# generators, which is a poor trait for something on the release path.
GOMOBILE_VERSION="v0.0.0-20260709172247-6129f5bee9d5"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENGINE_DIR="$REPO_ROOT/sshengine"
DIST_DIR="$ENGINE_DIR/dist"
# The wharf-ssh Expo module consumes the binds from here. The iOS xcframework copy
# is committed (so an iOS build needs no Go toolchain); the Android .aar is not.
MODULE_IOS_DIR="$REPO_ROOT/modules/wharf-ssh/ios"
MODULE_ANDROID_LIBS_DIR="$REPO_ROOT/modules/wharf-ssh/android/libs"

# --- argument parsing ------------------------------------------------------
want_ios=""
want_android=""
while [ $# -gt 0 ]; do
  case "$1" in
    --ios)     want_ios=1 ;;
    --android) want_android=1 ;;
    --all)     want_ios=1; want_android=1 ;;
    -h|--help)
      sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *)
      echo "!! unknown argument: $1 (try --help)" >&2
      exit 2 ;;
  esac
  shift
done
# No target flags => build everything available, the historical behaviour. In that
# implicit mode a missing toolchain is a skip, not an error (a Mac with no Android
# SDK still builds iOS); an explicitly requested target that can't build is fatal.
explicit_target=1
if [ -z "$want_ios" ] && [ -z "$want_android" ]; then
  want_ios=1
  want_android=1
  explicit_target=""
fi

echo "==> Wharf SSH engine build"
echo "    engine: $ENGINE_DIR"
echo "    targets:$([ -n "$want_ios" ] && echo " ios")$([ -n "$want_android" ] && echo " android")"

# --- toolchain -------------------------------------------------------------
# Gradle (and Android Studio in particular) can invoke this with a login-shell PATH
# that omits the usual Go install locations, so probe them before giving up.
if ! command -v go >/dev/null 2>&1; then
  for candidate in /opt/homebrew/bin /usr/local/bin /usr/local/go/bin "$HOME/go/bin"; do
    if [ -x "$candidate/go" ]; then
      export PATH="$candidate:$PATH"
      break
    fi
  done
fi
if ! command -v go >/dev/null 2>&1; then
  echo "!! go toolchain not found on PATH" >&2
  echo "   The SSH engine is built from source (sshengine/); install Go to continue." >&2
  exit 1
fi
echo "    go:     $(go version)"

# gomobile/gobind must be on PATH. Install into GOBIN if missing or off-pin.
GOBIN="$(go env GOBIN)"
[ -n "$GOBIN" ] || GOBIN="$(go env GOPATH)/bin"
export PATH="$GOBIN:$PATH"

# `gomobile version` self-tests against a go.mod in cwd and often prints noise;
# the x/mobile module version baked into the binary is the meaningful number.
installed_gomobile_version() {
  command -v gomobile >/dev/null 2>&1 || return 1
  go version -m "$(command -v gomobile)" 2>/dev/null \
    | awk '$1=="mod" && $2=="golang.org/x/mobile"{print $3}'
}

current_ver="$(installed_gomobile_version || true)"
if [ "$current_ver" != "$GOMOBILE_VERSION" ]; then
  echo "==> installing pinned gomobile + gobind ($GOMOBILE_VERSION; found: ${current_ver:-none})"
  go install "golang.org/x/mobile/cmd/gomobile@$GOMOBILE_VERSION"
  go install "golang.org/x/mobile/cmd/gobind@$GOMOBILE_VERSION"
fi
echo "    gomobile: golang.org/x/mobile $(installed_gomobile_version || echo unknown)"

# gomobile needs its NDK/toolchain state initialized once. Cheap to re-run.
echo "==> gomobile init"
gomobile init

mkdir -p "$DIST_DIR"
cd "$ENGINE_DIR"

# gomobile resolves the golang.org/x/mobile bind runtime from the module graph.
go get golang.org/x/mobile/bind >/dev/null 2>&1 || true

ios_ok="skipped"
android_ok="skipped"

# --- iOS -------------------------------------------------------------------
# Requires Xcode. iossimulator target keeps it usable on Apple-silicon sims.
if [ -n "$want_ios" ]; then
  if command -v xcodebuild >/dev/null 2>&1; then
    echo "==> building iOS xcframework"
    if gomobile bind -target ios,iossimulator -o "$DIST_DIR/WharfSshEngine.xcframework" . ; then
      ios_ok="ok"
      # Sync the fresh xcframework into the Expo module (the committed copy an iOS
      # build/CI links, so no Go toolchain is needed there).
      echo "==> syncing xcframework into $MODULE_IOS_DIR"
      mkdir -p "$MODULE_IOS_DIR"
      rsync -a --delete "$DIST_DIR/WharfSshEngine.xcframework" "$MODULE_IOS_DIR/"
    else
      ios_ok="FAILED"
    fi
  else
    echo "==> iOS: skipped (xcodebuild not found)"
  fi
fi

# --- Android ---------------------------------------------------------------
# Checks the SDK-root layouts used by the Android SDK on macOS, Linux and the EAS
# Build workers, not just the macOS default, so CI can find the NDK too.
detect_ndk() {
  if [ -n "${ANDROID_NDK_HOME:-}" ] && [ -d "${ANDROID_NDK_HOME}" ]; then
    echo "$ANDROID_NDK_HOME"; return 0
  fi
  if [ -n "${ANDROID_NDK_ROOT:-}" ] && [ -d "${ANDROID_NDK_ROOT}" ]; then
    echo "$ANDROID_NDK_ROOT"; return 0
  fi
  local base
  for base in "${ANDROID_HOME:-}/ndk" "${ANDROID_SDK_ROOT:-}/ndk" \
              "$HOME/Library/Android/sdk/ndk" "$HOME/Android/Sdk/ndk"; do
    case "$base" in /ndk) continue ;; esac  # unset var collapsed to bare "/ndk"
    if [ -d "$base" ]; then
      # newest installed NDK
      local latest
      latest="$(ls -1 "$base" 2>/dev/null | sort -V | tail -1)"
      if [ -n "$latest" ]; then echo "$base/$latest"; return 0; fi
    fi
  done
  return 1
}

if [ -n "$want_android" ]; then
  if NDK="$(detect_ndk)"; then
    echo "==> building Android aar (NDK: $NDK)"
    export ANDROID_NDK_HOME="$NDK"
    if gomobile bind -target android -androidapi 24 -o "$DIST_DIR/sshengine.aar" . ; then
      android_ok="ok"
      # Sync the fresh aar into the Expo module. This copy is NOT committed (it is
      # regenerated on demand by the module's Gradle preBuild hook).
      echo "==> syncing sshengine.aar into $MODULE_ANDROID_LIBS_DIR"
      mkdir -p "$MODULE_ANDROID_LIBS_DIR"
      rsync -a "$DIST_DIR/sshengine.aar" "$MODULE_ANDROID_LIBS_DIR/"
    else
      android_ok="FAILED"
      # gomobile leaves a 0-byte aar behind on failure; a later build would happily
      # link the empty file and fail much further from the cause.
      rm -f "$DIST_DIR/sshengine.aar"
    fi
  elif [ -n "$explicit_target" ]; then
    echo "!! Android: no NDK found" >&2
    echo "   Set ANDROID_NDK_HOME, or install one via:" >&2
    echo "     sdkmanager --sdk_root=\"\$ANDROID_HOME\" 'ndk;27.1.12297006'" >&2
    android_ok="FAILED"
  else
    echo "==> Android: skipped (no NDK found; set ANDROID_NDK_HOME or install one)"
  fi
fi

# --- summary ---------------------------------------------------------------
echo
echo "==> build summary"
echo "    iOS:     $ios_ok"
echo "    Android: $android_ok"
if [ -d "$DIST_DIR" ]; then
  echo "    artifacts:"
  du -sh "$DIST_DIR"/* 2>/dev/null || echo "      (none)"
fi

# Fail the script if a target that was attempted failed.
if [ "$ios_ok" = "FAILED" ] || [ "$android_ok" = "FAILED" ]; then
  exit 1
fi
